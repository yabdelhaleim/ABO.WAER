<?php

namespace App\Notifications;

use App\Enums\CampaignType;
use App\Models\Campaign;
use Illuminate\Notifications\Messages\MailMessage;
use Illuminate\Notifications\Notification;
use Illuminate\Support\Facades\Log;
use NotificationChannels\WebPush\WebPushChannel;
use NotificationChannels\WebPush\WebPushMessage;

/**
 * The unified delivery class for a marketing campaign.
 *
 * Phase 7 · Step 4 wires this notification in for every channel the campaign
 * supports. The channel selection is decided on the campaign's `type` so the
 * dispatcher never has to know which transport is being used:
 *
 *   - Email -> delivered via the mail channel using a branded HTML mailable.
 *   - Push  -> persisted to the `notifications` table through Laravel's
 *              `database` channel and shown on the customer's account dashboard.
 *   - Sms   -> not enabled by default. The send is captured in the application
 *              log with a stable, isolated format so the operations team can
 *              audit what would have gone out without actually dispatching
 *              messages through a 3rd party yet.
 *
 * The notification itself is intentionally cheap (no job, no queue) — the
 * outer SendCampaignJob already owns the chunked walk and the retry policy,
 * so inflating each individual send with another queue hop would just make
 * a 50,000-recipient run slower without giving us any extra resilience.
 */
class CampaignNotification extends Notification
{
    public function __construct(public Campaign $campaign) {}

    /**
     * Routing key per campaign type. Returns the array of channel names
     * Laravel will resolve into MailMessage/DatabaseMessage/etc.
     *
     * @return array<int, string>
     */
    public function via(mixed $notifiable): array
    {
        return match ($this->campaign->type) {
            CampaignType::Email => ['mail'],
            CampaignType::Push => ['database', WebPushChannel::class],
            CampaignType::Sms => $this->smsLogChannel($notifiable),
        };
    }

    /**
     * WebPush payload for customer mobile/desktop push notification.
     */
    public function toWebPush(mixed $notifiable, mixed $notification): WebPushMessage
    {
        $url = $this->campaignCtaUrl();

        $body = $this->campaign->message;
        if ($this->campaign->coupon) {
            $body .= ' | Use code: '.$this->campaign->coupon;
        }

        $push = (new WebPushMessage)
            ->title($this->campaign->title)
            ->icon(asset('images/abo-icon-192.png'))
            ->badge(asset('images/abo-badge-96.png'))
            ->body($body)
            ->action('Shop Now', 'shop_now')
            ->data(['url' => $url])
            ->tag('campaign-'.$this->campaign->id)
            ->vibrate([200, 100, 200]);

        if ($this->campaign->image_url) {
            $push->image($this->campaign->image_url);
        }

        return $push;
    }

    /**
     * The mail channel payload. The mailable renders a branded Blade view
     * that embeds the open-tracking pixel and rewrites CTA links through
     * the click tracker — every send therefore counts into the campaign's
     * opened_count / clicked_count automatically.
     */
    public function toMail(mixed $notifiable): MailMessage
    {
        return (new MailMessage)
            ->subject($this->campaign->subject)
            ->view('emails.campaign', [
                'campaign' => $this->campaign,
                'customer' => $notifiable,
                'coupon' => $this->campaign->coupon,
            ]);
    }

    /**
     * The database channel payload. Each entry stores everything the
     * dashboard needs to render the bell-icon row without re-querying the
     * campaign table, and keeps a stable `type` so frontend code can
     * switch on what kind of push it is.
     *
     * @return array<string, mixed>
     */
    public function toDatabase(mixed $notifiable): array
    {
        return [
            'campaign_id' => $this->campaign->id,
            'title' => $this->campaign->title,
            'message' => $this->campaign->message,
            'url' => $this->campaignCtaUrl(),
            'type' => $this->campaign->type->value,
        ];
    }

    /**
     * SMS is not enabled by default — the gateway is left to a later phase.
     * For now the campaign's "send" still has to produce an audit-worthy
     * record, so we route through the application log and return an empty
     * channel list. This keeps the campaign's counters honest (no sent
     * rows were ever generated by an unknown transport) while we wait for
     * the SMS driver to be wired in.
     *
     * @return array<int, string>
     */
    protected function smsLogChannel(mixed $notifiable): array
    {
        Log::info('Campaign SMS dispatched (channel disabled).', [
            'campaign_id' => $this->campaign->id,
            'campaign_type' => $this->campaign->type->value,
            'notifiable_id' => $notifiable->getKey(),
            'notifiable_type' => $notifiable->getMorphClass(),
        ]);

        return [];
    }

    /**
     * The URL the CTA and push notification link to. The mail view rewrites
     * this through the click tracker so every click can be counted; the
     * raw URL is what the database channel stores because push notifications
     * are opened on the device directly without a redirect server hop.
     */
    public function campaignCtaUrl(): string
    {
        return url('/shop');
    }
}
