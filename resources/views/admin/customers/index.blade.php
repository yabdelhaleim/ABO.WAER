@php
    // TODO(backend): replace the static generation below with data
    // fetched server-side from the customers / orders / addresses
    // tables. The view shape is final; only the data source changes.

    // Today is the page's "now" — matches dashboard, orders and
    // the date used in the AGENTS.md currentDate.
    $today = '2026-10-16';

    // Governorates reused from the orders page so a customer can
    // plausibly appear in both lists.
    $governorates = ['Cairo', 'Giza', 'Alexandria', 'Dakahlia', 'Sharqia'];

    $citiesByGovernorate = [
        'Cairo'      => ['Maadi', 'Nasr City', 'Heliopolis', 'Dokki', 'Mohandessin', 'New Cairo', 'Zamalek', 'Ain Shams'],
        'Giza'       => ['Haram', 'Sheikh Zayed', '6 October', 'Faisal', 'Imbaba', 'Agouza'],
        'Alexandria' => ['Sidi Gaber', 'Roushdy', 'Smouha', 'Gleem', 'Mandara', 'Miami'],
        'Dakahlia'   => ['Mansoura', 'Talkha', 'Mit Ghamr', 'Dekernes', 'Belqas', 'Sherbin'],
        'Sharqia'    => ['Zagazig', '10th of Ramadan', 'Bilbeis', 'Minya El-Qamh', 'Abu Hammad', 'Kafr Sakr'],
    ];

    // 40 first + last name pairs. Some overlap with the orders
    // names list is intentional so a customer name from the
    // orders page could plausibly appear in the customers list.
    $names = [
        ['Yara', 'Hassan'],         ['Ahmed', 'Mohamed'],
        ['Salma', 'Ali'],           ['Omar', 'Ibrahim'],
        ['Mariam', 'Farouk'],       ['Karim', 'Nassar'],
        ['Yasmin', 'Aziz'],         ['Mahmoud', 'Said'],
        ['Heba', 'Khalil'],         ['Ali', 'Sabry'],
        ['Rana', 'Hamdy'],          ['Tamer', 'Zaki'],
        ['Hagar', 'Soliman'],       ['Sherif', 'Saleh'],
        ['Aya', 'Adel'],            ['Hossam', 'Mohsen'],
        ['Nada', 'Farag'],          ['Mostafa', 'Nasser'],
        ['Reem', 'Saad'],           ['Tarek', 'Galal'],
        ['Dalia', 'Mounir'],        ['Waleed', 'Ramzy'],
        ['Esraa', 'Fathy'],         ['Youssef', 'Lotfy'],
        ['Shaimaa', 'Bekhet'],      ['Amr', 'Helmy'],
        ['Menna', 'Khattab'],       ['Maged', 'Ezzat'],
        ['Nada', 'Sami'],           ['Ibrahim', 'Gaber'],
        ['Nour', 'El-Sayed'],       ['Bassel', 'Ramadan'],
        ['Hala', 'Hafez'],          ['Khaled', 'Antar'],
        ['Rania', 'Salem'],         ['Hazem', 'Mansour'],
        ['Soha', 'Naguib'],         ['Fady', 'Rizk'],
        ['Lina', 'Awad'],           ['Adham', 'Saeed'],
        ['Passant', 'Magdy'],       ['Seif', 'Tawfik'],
    ];

    $streets   = ['Street 9', 'Road 12', 'El-Nil St', 'Tahrir Square area', 'El-Horreya St', 'Pyramids Road', 'El-Geish St', 'Corniche'];
    $buildings = ['Building 4', 'Tower B', 'Villa 7', 'Floor 2', 'Block 11', 'Plaza 3', 'House 14'];

    // Carrier codes for the deterministic phone generation.
    $carriers = ['10', '11', '12', '15'];

    // Two blocked customers per the spec. Indices are 0-based into
    // the final customer array.
    $blockedIndices = [7, 23];

    // A small mix of order statuses the customer's recent orders
    // can carry — we re-use the same status catalogue as the
    // orders page so the order-history block stays consistent.
    $orderStatuses = ['new', 'processing', 'shipped', 'delivered', 'delivered', 'delivered', 'cancelled', 'returned'];

    // Seed the loop deterministically so the page is the same
    // every load — same trick as the orders page.
    mt_srand(20261016);

    // ─── Customer generation ────────────────────────────────────
    $customers = [];
    for ($i = 0; $i < 40; $i++) {
        $namePair    = $names[$i];
        $firstName   = $namePair[0];
        $lastName    = $namePair[1];
        $name        = $firstName . ' ' . $lastName;
        $initials    = strtoupper(substr($firstName, 0, 1) . substr($lastName, 0, 1));

        // Phone: 01X XXXX XXXX (carrier + 8 digits).
        $carrier     = $carriers[$i % count($carriers)];
        $phoneRaw    = '0' . $carrier . str_pad((string) mt_rand(10000000, 99999999), 8, '0', STR_PAD_LEFT);
        $phone       = preg_replace('/^(\d{4})(\d{4})(\d{4})$/', '$1 $2 $3', $phoneRaw);

        // Email — built from the name + a domain.
        $emailLocal  = strtolower($firstName . '.' . str_replace('-', '', $lastName));
        $emailDomain = $i % 3 === 0 ? 'example.com' : ($i % 3 === 1 ? 'mailbox.org' : 'inbox.dev');
        $email       = $emailLocal . '@' . $emailDomain;

        $governorate = $governorates[$i % count($governorates)];
        $city        = $citiesByGovernorate[$governorate][($i + 2) % count($citiesByGovernorate[$governorate])];

        // Orders count spread 0..12 with a heavy tail toward the
        // lower end so the "no orders" and "new" buckets are not
        // empty. Blocked customers get realistic numbers too —
        // only the blocked flag changes, not the underlying data.
        $ordersCount = 0;
        $bucket      = $i % 10;
        if ($bucket === 0)        $ordersCount = 0;
        elseif ($bucket === 1)    $ordersCount = 1;
        elseif ($bucket === 2)    $ordersCount = 2;
        elseif ($bucket === 3)    $ordersCount = 3;
        elseif ($bucket === 4)    $ordersCount = 4;
        elseif ($bucket === 5)    $ordersCount = 6;
        elseif ($bucket === 6)    $ordersCount = 8;
        elseif ($bucket === 7)    $ordersCount = 10;
        elseif ($bucket === 8)    $ordersCount = 12;
        else                      $ordersCount = 5;

        // Total spent — roughly EGP 0..24,000. Customers with
        // 0 orders have 0; otherwise a random amount that grows
        // with order count but stays in range.
        if ($ordersCount === 0) {
            $totalSpent = 0;
        } else {
            // Avg per order: EGP 450..1800, slightly higher for
            // customers with more orders to give the "VIP"
            // segment natural high spenders.
            $perOrderBase = 450 + ($ordersCount * 60);
            $perOrder     = mt_rand($perOrderBase, $perOrderBase + 800);
            $totalSpent   = min(24000, max(450, $ordersCount * $perOrder));
        }

        // Sign-up date — somewhere in the last 12 months. Some
        // customers in the last 30 days so "New this month" is
        // not zero.
        $daysAgo = $i % 10 === 0 ? mt_rand(0, 14) : mt_rand(0, 360);
        $signup  = date('Y-m-d', strtotime($today) - ($daysAgo * 86400));

        // Last order — null for 0-order customers, otherwise
        // between signup and today.
        if ($ordersCount === 0) {
            $lastOrder = null;
        } else {
            $lastOrderDaysAgo = max(0, $daysAgo - mt_rand(0, max(1, $daysAgo)));
            $lastOrder = date('Y-m-d', strtotime($today) - ($lastOrderDaysAgo * 86400));
        }

        // Language: AR is the default for the Egyptian market, EN
        // for a small minority.
        $language = $i % 5 === 0 ? 'EN' : 'AR';

        // Saved addresses (1 or 2).
        $addressCount = $i % 3 === 0 ? 1 : 2;
        $addresses = [];
        for ($a = 0; $a < $addressCount; $a++) {
            $addresses[] = [
                'label'       => $a === 0 ? 'Home' : 'Work',
                'governorate' => $a === 1 && $i % 4 === 0
                    ? $governorates[($i + 1) % count($governorates)]
                    : $governorate,
                'city'        => $a === 1 && $i % 4 === 0
                    ? $citiesByGovernorate[$governorates[($i + 1) % count($governorates)]][$i % 5]
                    : $city,
                'street'      => $streets[($i + $a) % count($streets)],
                'building'    => $buildings[($i + $a) % count($buildings)],
                'isDefault'   => $a === 0,
            ];
        }

        // Recent order history — last up to 5 orders (newest first).
        $recentOrders = [];
        for ($k = 0; $k < min(5, $ordersCount); $k++) {
            $orderNum     = 1042 - $k - ($i % 3);
            $orderDaysAgo = $lastOrderDaysAgo !== null
                ? max(0, $lastOrderDaysAgo + ($k * mt_rand(7, 21)))
                : 0;
            $orderDate    = date('Y-m-d', strtotime($today) - ($orderDaysAgo * 86400));
            $orderTotal   = $ordersCount === 0
                ? 0
                : max(450, (int) round(($totalSpent / $ordersCount) + mt_rand(-200, 400)));
            $orderStatus  = $orderStatuses[($i + $k) % count($orderStatuses)];
            $recentOrders[] = [
                'number' => '#' . $orderNum,
                'date'   => $orderDate,
                'total'  => $orderTotal,
                'status' => $orderStatus,
            ];
        }

        $customers[] = [
            'id'             => (string) (5000 + $i + 1),
            'name'           => $name,
            'firstName'      => $firstName,
            'lastName'       => $lastName,
            'initials'       => $initials,
            'phone'          => $phone,
            'email'          => $email,
            'language'       => $language,
            'governorate'    => $governorate,
            'ordersCount'    => $ordersCount,
            'totalSpent'     => $totalSpent,
            'signupDate'     => $signup,
            'lastOrder'      => $lastOrder,
            'blocked'        => in_array($i, $blockedIndices, true),
            'addresses'      => $addresses,
            'recentOrders'   => $recentOrders,
            'tags'           => [],
            'note'           => '',
        ];
    }

    // ─── Derived stats (server-computed from the sample array) ──
    $totalCustomers = count($customers);
    $thirtyDaysAgo  = date('Y-m-d', strtotime($today . ' -30 days'));
    $newThisMonth   = count(array_filter($customers, fn ($c) => $c['signupDate'] >= $thirtyDaysAgo));

    $returningCount = count(array_filter($customers, fn ($c) => ! $c['blocked'] && $c['ordersCount'] >= 2 && $c['ordersCount'] <= 4));
    $returningPct   = $totalCustomers > 0 ? (int) round(($returningCount / $totalCustomers) * 100) : 0;

    $totalOrdersAll   = array_sum(array_column($customers, 'ordersCount'));
    $totalSpentAll    = array_sum(array_column($customers, 'totalSpent'));
    $avgOrderValue    = $totalOrdersAll > 0 ? (int) round($totalSpentAll / $totalOrdersAll) : 0;

    $customersJson = json_encode($customers, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
@endphp

